// B4 (llms.txt adoption) and B2 (AI bot robots.txt census) from crawl.jsonl.
import { readFileSync, writeFileSync } from "node:fs";
import robotsParser from "robots-parser";
import { readJsonl } from "./jsonl.mjs";

const domains = new Map(JSON.parse(readFileSync("domains.json", "utf8")).map((d) => [d.host, d]));
const crawl = [];
for await (const r of readJsonl("crawl.jsonl")) {
  if (!domains.has(r.host)) continue;
  // keep only what the analysis reads, so memory stays small
  if (r.llmsFull?.text) r.llmsFull.text = r.llmsFull.text.slice(0, 2048);
  crawl.push(r);
}

const isHtml = (r) =>
  /text\/html|application\/xhtml/i.test(r.contentType ?? "") ||
  /^\s*(<!doctype|<html|<head|<body|<\?xml|<)/i.test(r.text ?? "");
const challenged = (r) =>
  !!r.cfMitigated ||
  /just a moment|cf-chl|challenge-platform|captcha|access denied|attention required|verify you are human|px-captcha|_Incapsula_|perimeterx|datadome/i.test(
    r.text ?? "",
  );

/** Catch-all or error responses that aren't an llms.txt at all (e.g. "OK", an IP, a 404 message, a GIF). */
function junk(r, body) {
  const ct = (r.contentType ?? "").toLowerCase();
  const startsMd = /^#/.test(body);
  if (ct && !/text|markdown/.test(ct) && !startsMd) return true;
  if (body.length < 20 && !startsMd) return true;
  if (
    body.length < 300 &&
    /page not found|not found|could not be found|route not found|system error/i.test(body)
  )
    return true;
  if (body.length < 300 && /^[\[{]/.test(body)) return true;
  return false;
}

function classifyFile(r, expectPath) {
  if (!r) return "unreachable";
  if (!r.ok) return r.error === "TimeoutError" ? "timeout" : "neterror";
  if (r.status === 200) {
    const body = (r.text ?? "").replace(/^﻿/, "").trim();
    if (!body) return "empty";
    if (isHtml(r)) return challenged(r) ? "blocked" : "html";
    if (junk(r, body)) return "junk";
    return "file";
  }
  if ([401, 403, 429, 503].includes(r.status))
    return challenged(r) || r.status !== 503 ? "blocked" : "error";
  if ([404, 410].includes(r.status)) return "none";
  if (r.status >= 500) return "error";
  return "other";
}

/* ---------------- B4: llms.txt ---------------- */

function stripFences(text) {
  return text.replace(/```[\s\S]*?```/g, "");
}

function lint(text) {
  const t = stripFences(text.replace(/^﻿/, ""));
  const lines = t.split(/\r?\n/);
  const nonEmpty = lines.filter((l) => l.trim());
  const first = nonEmpty[0] ?? "";
  const h1 = lines.filter((l) => /^#\s+\S/.test(l));
  const h2 = lines.filter((l) => /^##\s+\S/.test(l));
  const h3plus = lines.filter((l) => /^#{3,}\s+\S/.test(l));
  const links = [...t.matchAll(/\[([^\]]*)\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)].map((m) => m[2]);
  const listLinks = lines.filter((l) => /^\s*[-*+]\s*\[[^\]]+\]\([^)]+\)/.test(l));
  const bareUrls = [...t.matchAll(/(?<!\()https?:\/\/[^\s)>\]]+/g)].length;
  const head = text.slice(0, 4000);
  const gen = /generated by yoast seo/i.test(head)
    ? "Yoast SEO"
    : /generated by rank math/i.test(head)
      ? "Rank Math"
      : /generated by all in one seo/i.test(head)
        ? "All in One SEO"
        : /hostinger tools plugin/i.test(head)
          ? "Hostinger Tools"
          : /powered by Wix and supports the Model Context Protocol/i.test(head)
            ? "Wix"
            : /^#\s+Agent Instructions/m.test(head) &&
                /shop\.app\/SKILL\.md|Commerce Protocol/i.test(text)
              ? "Shopify agent template"
              : null;
  return {
    gen,
    h1First: /^#\s+\S/.test(first),
    h1Count: h1.length,
    blockquote: lines.some((l) => /^>\s*\S/.test(l)),
    h2Count: h2.length,
    h3plus: h3plus.length,
    links: links.length,
    listLinks: listLinks.length,
    relativeLinks: links.filter((u) => !/^(https?:|mailto:|#)/i.test(u)).length,
    mdLinks: links.filter((u) => /\.md(#.*)?$/i.test(u)).length,
    bareUrls,
    optional: lines.some((l) => /^##\s+optional\s*$/i.test(l)),
    robotsSyntax: /^\s*(user-agent|disallow|allow)\s*:/im.test(t),
    htmlTags: /<(div|p|br|a|span|script|meta|table|img)\b[^>]*>/i.test(t),
    noStructure: h1.length === 0 && h2.length === 0 && links.length === 0,
    firstLine: first.slice(0, 120),
    linkSample: links.filter((u) => /^https?:/i.test(u)).slice(0, 5),
  };
}

const segOf = (d) => {
  const s = [];
  if (d.segs.f500) s.push("f500", `f500:${d.segs.f500.sector}`);
  if (d.segs.saas) s.push("saas", `saas:${d.segs.saas.seg}`);
  if (d.segs.top10k) s.push("top10k", d.rank <= 1000 ? "top10k:1-1k" : "top10k:1k-10k");
  if (d.segs.news) s.push("news");
  if (d.segs.ecom) s.push("ecom");
  if (d.segs.news || d.segs.ecom) s.push("news+ecom");
  return s;
};

const hosts = [];
for (const r of crawl) {
  const d = domains.get(r.host);
  if (r.fatal) {
    hosts.push({ host: r.host, segs: segOf(d), reachable: false });
    continue;
  }
  const reachable = !!r.robots?.ok;
  const llms = classifyFile(r.llms);
  const full = classifyFile(r.llmsFull);
  const robotsState = classifyFile(r.robots);
  const h = {
    host: r.host,
    rank: d.rank,
    segs: segOf(d),
    reachable,
    llms,
    full,
    robotsState,
    llmsFinalUrl: r.llms?.finalUrl,
    llmsCT: r.llms?.contentType,
    llmsBytes: r.llms?.bytes,
    fullBytes: r.llmsFull?.bytes,
    fullCT: r.llmsFull?.contentType,
    server: r.robots?.server ?? r.llms?.server,
  };
  if (
    llms === "file" &&
    /currently listed for sale|domain name is for sale|this domain (name )?is for sale|buy this domain/i.test(
      r.llms.text.slice(0, 3000),
    )
  ) {
    h.parked = true;
  }
  if (llms === "file") {
    h.lint = lint(r.llms.text);
    h.llmsRedirectedAway =
      r.llms.finalUrl && !/\/llms\.txt$/i.test(new URL(r.llms.finalUrl).pathname);
  }
  if (full === "file") h.fullStart = (r.llmsFull.text ?? "").slice(0, 200);
  // B2 robots
  if (robotsState === "file") h.robots = r.robots.text;
  hosts.push(h);
}

