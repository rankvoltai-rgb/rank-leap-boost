function robotsFacts(host, text) {
  const url = `https://${host}/robots.txt`;
  const rp = robotsParser(url, text);
  const agents = [...text.matchAll(/^\s*user-agent\s*:\s*(.+?)\s*(#.*)?$/gim)].map((m) =>
    m[1].toLowerCase(),
  );
  const facts = {};
  for (const [bot] of BOTS) {
    const root = rp.isDisallowed(`https://${host}/`, bot);
    const deep = rp.isDisallowed(`https://${host}/rankbox-probe-page-7q`, bot);
    const named = agents.some((a) => a === bot.toLowerCase() || a.includes(bot.toLowerCase()));
    facts[bot] = { full: root && deep, partial: !(root && deep) && (root || deep), named };
  }
  const allBlocked =
    rp.isDisallowed(`https://${host}/`, "SomeRandomBot") &&
    rp.isDisallowed(`https://${host}/rankbox-probe-page-7q`, "SomeRandomBot");
  return {
    facts,
    wildcardFull: allBlocked,
    contentSignal: /^\s*content-signal\s*:/im.test(text),
    contentSignalLines: [...text.matchAll(/^\s*content-signal\s*:\s*(.+)$/gim)].map((m) =>
      m[1].trim().toLowerCase(),
    ),
    mentionsLlmsTxt: /llms\.txt/i.test(text),
    cfManaged: /BEGIN Cloudflare Managed content/i.test(text),
    sitemaps: (text.match(/^\s*sitemap\s*:/gim) ?? []).length,
    bytes: text.length,
  };
}

for (const h of hosts) {
  if (h.robots) {
    h.rb = robotsFacts(h.host, h.robots);
    delete h.robots;
  }
}

